#!/usr/bin/env python3
"""Generate scratch scalar certificates for the pair-mass cell data.

The source tables remain unchanged. Each generated proof changes only the
selected right-hand table lookup to its literal, then proves the polynomial
arithmetic using norm_num. This script does not modify canonical Lean sources.
"""

import argparse
from fractions import Fraction
from pathlib import Path
import re


ROOT = Path(__file__).resolve().parents[3]
SOURCE = ROOT / "UnitDistance/PairMassDegree3DenseComputationCertificate.lean"
DEST = ROOT / ".cache/build-tmp/candidate20-cell-proof-test"
DATA = (ROOT / "UnitDistance/PairMassDegree3DenseData.lean").read_text()


def table(name):
    body = DATA.split("def " + name + " ", 1)[1].split("\ndef ", 1)[0]
    values = re.findall(r"\((-?\d+) : ℚ\) / (\d+)", body)
    assert len(values) == 64, (name, len(values))
    return values


def literal(value):
    return f"(({value[0]} : ℚ) / {value[1]})"


def rational(value):
    return Fraction(int(value[0]), int(value[1]))


tables = {
    label: table(f"pairMassCell{label}TableQ3")
    for label in ("Center", "Radius")
}
coefficient_source = (ROOT / "UnitDistance/PairMassCellCertificate.lean").read_text()
coefficient_body = coefficient_source.split("def pairPowerCoefficients :", 1)[1].split(
    "\n\n", 1
)[0]
matches = re.findall(
    r"\((-?\d+)\s*:\s*ℚ\)|(-?\d+)\s*/\s*(\d+)", coefficient_body
)
coefficients = [
    Fraction(int(integer)) if integer else Fraction(int(num), int(den))
    for integer, num, den in matches
]
assert len(coefficients) == 16, len(coefficients)


def polynomial(t, u):
    return sum(
        coefficients[a * 4 + b] * t**a * u**b
        for a in range(4)
        for b in range(4)
    )


for i in range(8):
    for j in range(8):
        lo = polynomial(Fraction(i, 8), Fraction(j, 8))
        hi = polynomial(Fraction(i + 1, 8), Fraction(j + 1, 8))
        assert (lo + hi) / 2 == rational(tables["Center"][i * 8 + j]), (i, j)
        assert (hi - lo) / (hi + lo) == rational(tables["Radius"][i * 8 + j]), (i, j)


def proof(label, i, j):
    return "\n".join([
        f"  change pairMassCell{label}Q {i} {j} = {literal(tables[label][i * 8 + j])}",
        f"  norm_num [pairMassCell{label}Q, pairMassPolynomialQ,",
        "    pairPowerCoefficients, Fin.sum_univ_succ]",
    ])


def scalar(label, i, j):
    return "\n".join([
        "set_option maxHeartbeats 1000000000 in",
        "set_option maxRecDepth 100000 in",
        f"private theorem pairMassCell{label}Scalar_{i}_{j} :",
        f"    pairMassCell{label}Q {i} {j} = pairMassCell{label}DataQ3 {i} {j} := by",
        proof(label, i, j),
        "",
    ])


def replacement(label):
    lines = [
        f"/- Scalar {label.lower()} certificates generated by",
        "verification/conditional-20260925/kernel-repair/generate-cell-certificates.py. -/",
        "",
    ]
    for i in range(8):
        for j in range(8):
            lines.append(scalar(label, i, j))
    lines.extend([
        "set_option maxHeartbeats 1000000000 in",
        "set_option maxRecDepth 100000 in",
        f"theorem pairMassCell{label}Q_eq_data (i j : Fin 8) :",
        f"    pairMassCell{label}Q i j = pairMassCell{label}DataQ3 i j := by",
        "  fin_cases i <;> fin_cases j",
    ])
    for i in range(8):
        for j in range(8):
            lines.append(f"  · exact pairMassCell{label}Scalar_{i}_{j}")
    return "\n".join(lines) + "\n"


def replace_certificate(source, label):
    old = "\n".join([
        "set_option maxHeartbeats 1000000000 in",
        "set_option maxRecDepth 100000 in",
        f"theorem pairMassCell{label}Q_eq_data (i j : Fin 8) :",
        f"    pairMassCell{label}Q i j = pairMassCell{label}DataQ3 i j := by",
        "  fin_cases i <;> fin_cases j <;> decide +kernel",
        "",
    ])
    generated = replacement(label)
    marker = f"/- Scalar {label.lower()} certificates generated by\n"
    theorem = f"theorem pairMassCell{label}Q_eq_data (i j : Fin 8) :"
    if source.count(theorem) != 1:
        raise ValueError(f"Expected public {label} theorem exactly once")
    if source.count(old) == 1 and marker not in source:
        return source.replace(old, generated, 1)
    if old not in source and source.count(marker) == 1:
        start = source.index(marker)
        public_start = source.index(theorem)
        end = source.find("\n\n", public_start)
        existing = source[start:] if end == -1 else source[start:end + 1]
        if existing == generated:
            return source
    raise ValueError(f"Expected original or exactly matching generated {label} proof")


def check_output_path(path):
    if path.resolve().is_relative_to((ROOT / "UnitDistance").resolve()):
        raise ValueError(f"Refusing canonical Lean output: {path}")
    if path.exists() and path.samefile(SOURCE):
        raise ValueError(f"Refusing output linked to the canonical source: {path}")


def write_new_or_identical(path, content):
    check_output_path(path)
    payload = content.encode("utf-8")
    if path.exists():
        if path.read_bytes() != payload:
            raise ValueError(f"Refusing to overwrite different existing content: {path}")
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("xb") as output:
        output.write(payload)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--tests-only", action="store_true")
    parser.add_argument(
        "--labels", nargs="+", choices=("Center", "Radius"),
        default=["Radius"],
        help="Select which existing public proof bodies to replace in the scratch module",
    )
    parser.add_argument("--source", type=Path, default=SOURCE)
    parser.add_argument(
        "--output", type=Path,
        default=DEST / "UnitDistance/PairMassDegree3DenseComputationCertificate.lean",
    )
    args = parser.parse_args()
    check_output_path(args.output)
    for label in ("Center", "Radius"):
        test = DEST / f"Cell{label}77.lean"
        write_new_or_identical(test, "\n".join([
            "import UnitDistance.PairMassDegree3DenseComputationCertificate",
            "namespace UnitDistance.Witness",
            "set_option maxHeartbeats 1000000000",
            "set_option maxRecDepth 100000",
            f"theorem cell{label}77 :",
            f"    pairMassCell{label}Q 7 7 = pairMassCell{label}DataQ3 7 7 := by",
            proof(label, 7, 7),
            f"#print axioms cell{label}77",
            "end UnitDistance.Witness",
            "",
        ]))
        print(test)
    if args.tests_only:
        return
    source = args.source.read_text()
    for label in args.labels:
        source = replace_certificate(source, label)
    write_new_or_identical(args.output, source)
    print(args.output)
    print(
        f"Generated {64 * len(args.labels)} scalar certificates; "
        "all data checked with exact Fraction arithmetic"
    )


if __name__ == "__main__":
    main()
