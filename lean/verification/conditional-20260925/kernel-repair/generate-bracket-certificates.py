#!/usr/bin/env python3
"""Regenerate a scratch DenseComputation module using exact scalar certificates.

All numerical inputs come from the existing DenseData tables. Python Fraction
checks are diagnostics; Lean checks each literal conversion and arithmetic proof.
The canonical source is read only. Output defaults to a fresh scratch file.
"""

from fractions import Fraction
from pathlib import Path
import re
import argparse


ROOT = Path(__file__).resolve().parents[3]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--output", type=Path, required=True)
args = parser.parse_args()
OUT = args.output
SOURCE = ROOT / "UnitDistance/PairMassDegree3DenseComputationCertificate.lean"
if OUT.resolve() == SOURCE.resolve():
    raise SystemExit("Refusing to overwrite canonical source")
DATA = (ROOT / "UnitDistance/PairMassDegree3DenseData.lean").read_text()


def table(name, count):
    body = DATA.split("def " + name + " ", 1)[1].split("\ndef ", 1)[0]
    values = re.findall(r"\((-?\d+) : ℚ\) / (\d+)", body)
    assert len(values) == count, (name, len(values), count)
    return values


def literal(value):
    numerator, denominator = value
    return f"(({numerator} : ℚ) / {denominator})"


def rational(value):
    return Fraction(int(value[0]), int(value[1]))


centers = table("pairMassCellCenterTableQ3", 64)
radii = table("pairMassCellRadiusTableQ3", 64)
scalars = table("pairMassBracketScalarTableQ3", 256)
labels = ["Constant", "Linear", "Quadratic", "Cubic"]
choose = [Fraction(1)]
p = Fraction(4000000, 2083647)
for k in range(4):
    choose.append(choose[-1] * (p - k) / (k + 1))


def formula(r, center, radius):
    if r == 0:
        return (
            "pairMassChooseQ 0 - pairMassChooseQ 1 + pairMassChooseQ 2 -\n"
            f"    pairMassChooseQ 3 + |pairMassChooseQ 4| * {radius} ^ 4 /\n"
            f"    (1 - {radius})"
        )
    if r == 1:
        return (
            "(pairMassChooseQ 1 - 2 * pairMassChooseQ 2 + 3 * pairMassChooseQ 3) *\n"
            f"    {center}⁻¹"
        )
    if r == 2:
        return f"(pairMassChooseQ 2 - 3 * pairMassChooseQ 3) * {center}⁻¹ ^ 2"
    return f"pairMassChooseQ 3 * {center}⁻¹ ^ 3"


lines = [
    "/- Exact bracket scalar certificates. Generated by",
    "verification/conditional-20260925/kernel-repair/generate-bracket-certificates.py.",
    "Each table lookup is converted definitionally to a rational literal; norm_num",
    "then proves the scalar equality. Splitting the proof avoids monolithic",
    "rational reduction during independent kernel checking. -/",
    "section",
    "set_option maxHeartbeats 1000000000",
    "set_option maxRecDepth 100000",
    "",
]

for r, label in enumerate(labels):
    for i in range(8):
        for j in range(8):
            index = i * 8 + j
            c, q = rational(centers[index]), rational(radii[index])
            expected = [
                choose[0] - choose[1] + choose[2] - choose[3]
                + abs(choose[4]) * q**4 / (1 - q),
                (choose[1] - 2 * choose[2] + 3 * choose[3]) / c,
                (choose[2] - 3 * choose[3]) / c**2,
                choose[3] / c**3,
            ][r]
            rhs = scalars[r * 64 + index]
            assert expected == rational(rhs), (r, i, j)
            lines.extend([
                f"private theorem pairMassBracketScalarCase_{r}_{i}_{j} :",
                f"    pairMassBracket{label}Q {i} {j} = pairMassBracketScalarDataQ3 {r} {i} {j} := by",
                (f"  simp only [pairMassBracket{label}Q, pairMassTailQ, pairMassCellRadiusQ_eq_data]"
                 if r == 0 else f"  simp only [pairMassBracket{label}Q, pairMassCellCenterQ_eq_data]"),
                "  change " + formula(r, literal(centers[index]), literal(radii[index]))
                + " =\n    " + literal(rhs),
                "  norm_num [pairMassChooseQ, pairMassPQ]",
                "",
            ])

for r, label in enumerate(labels):
    lines.extend([
        f"private theorem pairMassBracket{label}Cases_eq_data (i j : Fin 8) :",
        f"    pairMassBracket{label}Q i j = pairMassBracketScalarDataQ3 {r} i j := by",
        "  fin_cases i <;> fin_cases j",
    ])
    for i in range(8):
        for j in range(8):
            lines.append(f"  · exact pairMassBracketScalarCase_{r}_{i}_{j}")
    lines.append("")

lines.extend([
    "theorem pairMassBracketScalarsQ_eq_data (i j : Fin 8) :",
    "    #v[pairMassBracketConstantQ i j, pairMassBracketLinearQ i j,",
    "      pairMassBracketQuadraticQ i j, pairMassBracketCubicQ i j] =",
    "    Vector.ofFn fun r => pairMassBracketScalarDataQ3 r i j := by",
    "  apply Vector.ext",
    "  intro r hr",
    "  simp only [Vector.getElem_ofFn]",
    "  interval_cases r",
])
for r, label in enumerate(labels):
    lines.extend([
        f"  · change pairMassBracket{label}Q i j = pairMassBracketScalarDataQ3 {r} i j",
        f"    exact pairMassBracket{label}Cases_eq_data i j",
    ])
lines.extend(["", "end", ""])
source = SOURCE.read_text()
start = source.find("/- Exact bracket scalar certificates.")
if start < 0:
    start = source.index("set_option maxHeartbeats 1000000000 in\nset_option maxRecDepth 100000 in\ntheorem pairMassBracketScalarsQ_eq_data")
stop = source.index("def pairMassDenseBracket3", start)
OUT.parent.mkdir(parents=True, exist_ok=True)
with OUT.open("x") as stream:
    stream.write(source[:start] + "\n".join(lines) + "\n" + source[stop:])
print(f"Generated and numerically cross-checked 256 scalar proof statements: {OUT}")
