def main():
    d = run_gp()
    y = model_coords(d["yM"])
    assert len(y) == 16
    powers = {1: y}
    for exponent in range(2, 9):
        powers[exponent] = model_mul(powers[exponent - 1], y)
    pi2 = (Fraction(-6101, 2), Fraction(-393, 2)) + (Fraction(0),) * 14
    assert model_mul(pi2, model_coords(d["uM"])) == powers[8]
    power_coordinates = "\n\n".join(
        f"private def y{e}M : M4 :=\n" + split_element(model_literal(powers[e]))
        for e in range(2, 9))
    power_checks = "\n\n".join(
        "set_option maxRecDepth 100000 in\n"
        f"private theorem yM_step{e} : {'yM' if e == 2 else f'y{e - 1}M'} * yM = y{e}M "
        ":= by decide +kernel" for e in range(2, 9))
    kp = ast.literal_eval(d["KpL"])
    z = ast.literal_eval(d["ZL"])
    f = ast.literal_eval(d["fL"])
    h = ast.literal_eval(d["hL"])
    assert kp[0] == 1 and z[0] % 2 == 1 and f[-1] == 1 and h[-1] == 1 and f[0] == 2
    text = TEMPLATE.format(
        yM=split_element(d["yM"]),
        uM=split_element(d["uM"]),
        power_coordinates=power_coordinates,
        power_checks=power_checks,
        fL=wrap_list(f),
        hL=wrap_list(h),
        GL=wrap_list(ast.literal_eval(d["GL"])),
        Kp1L=wrap_list(kp[1:]),
        ZL=wrap_list(z),
        WL=wrap_list(ast.literal_eval(d["WL"])),
        Z0=z[0],
    )
    OUT.write_text(text)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
