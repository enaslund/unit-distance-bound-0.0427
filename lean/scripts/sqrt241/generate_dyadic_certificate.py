#!/usr/bin/env python3
"""Stream E (root discriminant): generate UnitDistance/Sqrt241/Discriminant/DyadicModel.lean.

Runs scripts/sqrt241/dyadic_certificate.gp (PARI/GP), which computes and checks
the dyadic certificate for the field F = Q(sqrt241, sqrt2, sqrt pi2', sqrt beta1):

* y  : a generator of the unique prime of F above p1 = (pi2) (e = 8, f = 1,
       different exponent 18), with norm 2;
* f  : the characteristic polynomial of y (monic, integer coefficients);
* f = X^8 G + 2 Kp with Kp(0) = 1, and f' = X^18 Z + f W with Z(0) odd;
* u  : the unit y^8 / pi2 and its characteristic polynomial h.

Usage (from lean-formalization/):
    python3 scripts/sqrt241/generate_dyadic_certificate.py
"""

import ast
import pathlib
import subprocess
from fractions import Fraction

ROOT = pathlib.Path(__file__).resolve().parents[2]
GP_SCRIPT = ROOT / "scripts" / "sqrt241" / "dyadic_certificate.gp"
OUT = ROOT / "UnitDistance" / "Sqrt241" / "Discriminant" / "DyadicModel.lean"


def run_gp():
    out = subprocess.run(["gp", "-q", str(GP_SCRIPT)], stdin=subprocess.DEVNULL,
                         capture_output=True, text=True, check=True).stdout
    data = {}
    for line in out.splitlines():
        if ":=" in line:
            key, value = line.split(":=", 1)
            data[key.strip()] = value.strip()
    return data


def wrap_list(items, indent="    "):
    lines = []
    cur = indent + "["
    for i, x in enumerate(items):
        piece = str(x) + (", " if i < len(items) - 1 else "]")
        if len(cur) + len(piece.rstrip()) > 100:
            lines.append(cur.rstrip())
            cur = indent + " " + piece
        else:
            cur += piece
    lines.append(cur)
    return "\n".join(lines)


def top_split(text):
    """Split ⟨A, B⟩ into (A, B) at the top-level comma."""
    assert text.startswith("⟨") and text.endswith("⟩")
    inner = text[1:-1]
    depth = 0
    for i, ch in enumerate(inner):
        if ch == "⟨":
            depth += 1
        elif ch == "⟩":
            depth -= 1
        elif ch == "," and depth == 0:
            return inner[:i].strip(), inner[i + 1:].strip()
    raise ValueError("no top-level comma")


def split_element(text):
    """Lay out an M4 literal ⟨⟨a, b⟩, ⟨c, d⟩⟩ (a, b, c, d in M2) on four lines."""
    lo, hi = top_split(text)
    a, b = top_split(lo)
    c, d = top_split(hi)
    return f"  ⟨⟨{a},\n    {b}⟩,\n   ⟨{c},\n    {d}⟩⟩"


def model_coords(text):
    """Read the rational coordinates of a nested quadratic-algebra literal."""
    if text.startswith("⟨"):
        lo, hi = top_split(text)
        return model_coords(lo) + model_coords(hi)
    return (Fraction(text.strip("()")),)


# Squares of r, t, g, s in the respective preceding algebras, in the same
# coordinate order as the GP certificate and the Lean model. These are only
# used to propose intermediate coordinates; Lean checks every multiplication.
MODEL_SQUARES = {
    2: (Fraction(241),),
    4: (Fraction(2), Fraction(0)),
    8: (Fraction(6101, 2), Fraction(-393, 2), Fraction(0), Fraction(0)),
    16: tuple(map(Fraction, (-25, 2, 0, 0, -139, -9, 0, 0))),
}


def model_mul(x, y):
    """Multiply rational coordinate vectors in the nested quadratic model."""
    assert len(x) == len(y)
    if len(x) == 1:
        return (x[0] * y[0],)
    n = len(x) // 2
    ac = model_mul(x[:n], y[:n])
    bdsq = model_mul(model_mul(x[n:], y[n:]), MODEL_SQUARES[len(x)])
    ad = model_mul(x[:n], y[n:])
    bc = model_mul(x[n:], y[:n])
    return tuple(a + b for a, b in zip(ac, bdsq)) + tuple(a + b for a, b in zip(ad, bc))


def model_literal(coords):
    """Format exact rational coordinates as a nested Lean constructor."""
    if len(coords) == 1:
        q = coords[0]
        return str(q.numerator) if q.denominator == 1 else f"({q.numerator}/{q.denominator})"
    n = len(coords) // 2
    return f"⟨{model_literal(coords[:n])}, {model_literal(coords[n:])}⟩"


