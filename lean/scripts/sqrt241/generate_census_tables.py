#!/usr/bin/env python3
"""Census tables of `UnitDistance/Sqrt241/Levels/Census.lean`.

  python3 scripts/sqrt241/generate_census_tables.py [--write | --check]

For each census prime p in {41, 47, 53, 59, 61, 67, 79, 83, 97} (split in
B = Q(sqrt 241)) the script takes the root a of X^2 - X - 60 mod p used by the
module (the smaller one), so that sbar = 2a - 1 is a square root of 241 mod p,
and for both signs eps = +1, -1 of the chosen p-adic square root of 241 it
computes the reduced square classes

    c'_k = (nA_k + nB_k * eps * sbar) mod p,    k = 0..7,

of the eight radicands alpha_k = (nA_k + nB_k sqrt 241)/2 (the class of alpha_k
is 2 c'_k), the Frobenius vector sv_k = [2 c'_k is a non-residue mod p] and the
square form S(sv) of the retained cocycle (`GroupData.retainedCocycleMasks`,
reproduced below). Every value is untrusted: the Lean module re-checks all of
them by `decide +kernel` (`censusData_valid`), including S(sv) != 0.

Without an option the script prints the per-prime tables and the Lean block.
In the module the block is enclosed by the lines
"-- BEGIN Generated by scripts/sqrt241/generate_census_tables.py — do not edit by hand."
and "-- END Generated by scripts/sqrt241/generate_census_tables.py.";
`--write` replaces it, `--check` exits with status 1 if it differs.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TARGET = ROOT / "UnitDistance/Sqrt241/Levels/Census.lean"
BEGIN = "-- BEGIN Generated by scripts/sqrt241/generate_census_tables.py — do not edit by hand."
END = "-- END Generated by scripts/sqrt241/generate_census_tables.py."

# 2 x radicandA and 2 x radicandB (the Lean definitions `nA`, `nB`).
nA = [-2, -142022136, -6101, 6101, 62, 62, 652, 652]
nB = [0, 9148450, -393, -393, -4, 4, -42, 42]
# Lower-triangular cocycle masks of the retained model (`GroupData.retainedCocycleMasks`).
masks = [[1, 0, 0, 0, 0, 0, 0, 0], [4, 2, 0, 0, 0, 0, 0, 0], [8, 256, 0, 0, 0, 0, 0, 0],
         [16, 512, 4096, 0, 0, 0, 0, 0], [32, 204, 2943, 4624, 0, 0, 0, 0],
         [64, 1024, 8, 8192, 16384, 0, 0, 0], [128, 2048, 4360, 2711, 4681, 19908, 0, 0],
         [1, 3530, 332, 16, 22806, 2444, 21708, 0]]
census = [41, 47, 53, 59, 61, 67, 79, 83, 97]


def cocycle(v, w):
    r = 0
    for i in range(8):
        for j in range(8):
            if v[i] and w[j]:
                r ^= masks[i][j]
    return r


def tables():
    out = {}
    for p in census:
        roots = [a for a in range(p) if (a * a - a - 60) % p == 0]
        assert len(roots) == 2, (p, roots)
        a = roots[0]
        assert (2 * a - 1) % p != 0
        sbar = (2 * a - 1) % p
        assert (sbar * sbar - 241) % p == 0
        res = {}
        for eps in (1, -1):
            c = []
            sv = []
            for k in range(8):
                cp = (nA[k] + nB[k] * eps * sbar) % p
                assert cp != 0
                ck = 2 * cp
                c.append(ck)
                leg = pow(ck % p, (p - 1) // 2, p)
                assert leg in (1, p - 1)
                sv.append(0 if leg == 1 else 1)
            sq = cocycle(sv, sv)
            assert sq != 0, (p, eps)
            res[eps] = (c, sv, sq)
        out[p] = (a, sbar, res)
    return out


def lv(xs):
    return "![" + ", ".join(str(x) for x in xs) + "]"


def lean_block(out):
    lines = []
    for p in census:
        a, _, res = out[p]
        cp = [c // 2 for c in res[1][0]]
        cm = [c // 2 for c in res[-1][0]]
        lines.append(f"  ⟨{p}, {a}, {lv(cp)}, {lv(cm)}, {lv(res[1][1])}, {lv(res[-1][1])}⟩")
    return (BEGIN + "\n"
            + "/-- The census data (generated by `scripts/sqrt241/generate_census_tables.py`). -/\n"
            + "def censusData : Fin 9 → CensusData := ![\n" + ",\n".join(lines) + "]\n"
            + END + "\n")


def replace_marked(text, new):
    b = text.index(BEGIN)
    e = text.index("\n", text.index(END, b)) + 1
    return text[:b] + new + text[e:]


def main():
    mode = sys.argv[1] if len(sys.argv) > 1 else None
    out = tables()
    block = lean_block(out)
    if mode is None:
        for p in census:
            a, sbar, res = out[p]
            print(p, "a=", a, "sbar=", sbar)
            for eps in (1, -1):
                c, sv, sq = res[eps]
                print("  eps", eps, "c=", c, "sv=", sv,
                      "svmask=", sum(b << i for i, b in enumerate(sv)), "S(sv)=", sq)
        print(block, end="")
        return
    old = TARGET.read_text()
    text = replace_marked(old, block)
    if mode == "--write":
        TARGET.write_text(text)
        print(("updated " if text != old else "unchanged ") + str(TARGET))
    elif mode == "--check":
        if text != old:
            print(f"{TARGET}: generated block differs", file=sys.stderr)
            sys.exit(1)
        print(f"{TARGET}: generated block up to date")
    else:
        sys.exit(f"unknown option {mode}")


if __name__ == "__main__":
    main()
