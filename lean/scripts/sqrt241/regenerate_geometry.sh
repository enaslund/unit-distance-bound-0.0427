#!/bin/bash
# Regenerate the generated modules of UnitDistance/Sqrt241/Geometry.
#
#   scripts/sqrt241/regenerate_geometry.sh [ANALYSIS_JSON [SCRATCH_DIR]]
#
# Works on the lean-formalization/ tree containing this script, with the ℚ
# development built: copy_geometry.py
# reads the ℚ sources under UnitDistance/ and their `.ilean` files under
# .lake/build. ANALYSIS_JSON defaults to the committed
# scripts/sqrt241/geometry_analysis.json (the output of scripts/sqrt241/Analyze.lean);
# SCRATCH_DIR (default: a new temporary directory) receives the raw copies and
# copy_report.json. Only repository files are read.
#
# The generated copies of the √7 leaves (QuadraticSeven*, ImaginarySevenUnramified)
# are not installed: their generalizations to a radicand `d` (QuadraticRoot*,
# ImaginaryRootUnramified) are hand-written, as are RateCore, GaloisFixedField and
# FixedBaseBridge. Every installed copy starts with the line
# "-- Generated by scripts/sqrt241/regenerate_geometry.sh — do not edit by hand."
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
analysis=$(realpath "${1:-$here/geometry_analysis.json}")
scratch=$(realpath "${2:-$(mktemp -d)}")
cd "$here/../.."
geom=UnitDistance/Sqrt241/Geometry
rm -rf "$scratch/gen"
mkdir -p "$scratch/gen"
python3 "$here/copy_geometry.py" "$analysis" "$scratch/gen"
for f in "$scratch"/gen/UnitDistance/Sqrt241/Geometry/*.lean; do
  b=$(basename "$f")
  case "$b" in
    QuadraticSeven*|ImaginarySevenUnramified.lean) ;;
    *) cp "$f" "$geom/$b" ;;
  esac
done
python3 "$here/postprocess_values.py" "$geom"
python3 "$here/postprocess_root.py" "$geom"/HeckeSigned*.lean \
  "$geom"/HeckeQuadraticContinuation.lean "$geom"/ImaginaryQuadraticContinuation.lean \
  > /dev/null
echo "regenerated $geom (raw copies and copy_report.json in $scratch/gen)"
